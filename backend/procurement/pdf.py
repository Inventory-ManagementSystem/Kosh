  dispatched = [fmt_datetime(shipment.dispatched_at) if shipment else "-"]
  expected = fmt_date(shipment.expected_delivery_date if shipment else po.delivery_date)
  if shipment:
    if shipment.tracking_note:
      dispatched.append(f"Tracking: {esc(shipment.tracking_note)}")
