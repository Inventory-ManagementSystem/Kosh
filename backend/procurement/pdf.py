from datetime import timedelta
from decimal import Decimal
from io import BytesIO
from zoneinfo import ZoneInfo

from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.enums import TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

IST = ZoneInfo("Asia/Kolkata")

INK = colors.HexColor("#1F2A44")
MUTED = colors.HexColor("#5B6478")
LINE = colors.HexColor("#D5D9E3")
HEAD_BG = colors.HexColor("#EEF1F7")
WARN = colors.HexColor("#9A5B00")

_base = getSampleStyleSheet()["Normal"]
TEXT = ParagraphStyle("text", parent=_base, fontName="Helvetica", fontSize=9.5, leading=13, textColor=INK)
SMALL = ParagraphStyle("small", parent=TEXT, fontSize=8, leading=10.5, textColor=MUTED)
LABEL = ParagraphStyle("label", parent=SMALL, fontName="Helvetica-Bold", fontSize=7.5, leading=10)
CELL = ParagraphStyle("cell", parent=TEXT, fontSize=9, leading=11.5)
CELL_R = ParagraphStyle("cell_r", parent=CELL, alignment=TA_RIGHT)
HEAD = ParagraphStyle("head", parent=CELL, fontName="Helvetica-Bold", fontSize=8, textColor=MUTED)
HEAD_R = ParagraphStyle("head_r", parent=HEAD, alignment=TA_RIGHT)
TITLE = ParagraphStyle("title", parent=TEXT, fontName="Helvetica-Bold", fontSize=18, leading=22)
SUB = ParagraphStyle("sub", parent=TEXT, fontSize=10.5, leading=14, textColor=MUTED)
H2 = ParagraphStyle("h2", parent=TEXT, fontName="Helvetica-Bold", fontSize=10.5, leading=14, spaceBefore=4)

PAGE_W = A4[0] - 36 * mm 


def esc(value):
  return (
    str(value if value is not None else "")
    .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
  )


def money(value, prefix=True):
  value = Decimal(value or 0).quantize(Decimal("0.01"))
  sign = "-" if value < 0 else ""
  whole, frac = f"{abs(value):.2f}".split(".")
  if len(whole) > 3:
    head, tail = whole[:-3], whole[-3:]
    groups = []
    while len(head) > 2:
      groups.insert(0, head[-2:])
      head = head[:-2]
    if head:
      groups.insert(0, head)
    whole = ",".join(groups + [tail])
  return f"{sign}{'Rs. ' if prefix else ''}{whole}.{frac}"


def fmt_date(value):
  return value.strftime("%d-%m-%Y") if value else "-"


def fmt_datetime(value):
  if not value:
    return "-"
  return value.astimezone(IST).strftime("%d-%m-%Y, %I:%M %p IST")


def pct(value):
  return f"{Decimal(value).normalize():f}%"


def _footer(canvas, doc):
  canvas.saveState()
  canvas.setFont("Helvetica", 7.5)
  canvas.setFillColor(MUTED)
  canvas.drawString(18 * mm, 10 * mm, f"Generated by Kosh on {fmt_datetime(timezone.now())}")
  canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
  canvas.restoreState()


def _build(title, story):
  buffer = BytesIO()
  doc = SimpleDocTemplate(
    buffer, pagesize=A4, title=title, author="Kosh",
    leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=18 * mm,
  )
  doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
  return buffer.getvalue()


def _header(title, number, status):
  left = [Paragraph(esc(title), TITLE), Paragraph(esc(number), SUB)]
  right = [
    Paragraph("STATUS", ParagraphStyle("sl", parent=LABEL, alignment=TA_RIGHT)),
    Paragraph(esc(status).upper(), ParagraphStyle("sv", parent=H2, alignment=TA_RIGHT)),
  ]
  table = Table([[left, right]], colWidths=[PAGE_W * 0.7, PAGE_W * 0.3])
  table.setStyle(TableStyle([
    ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ("LINEBELOW", (0, 0), (-1, 0), 1.2, INK),
    ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ("LEFTPADDING", (0, 0), (-1, -1), 0),
    ("RIGHTPADDING", (0, 0), (-1, -1), 0),
  ]))
  return table


def _info_grid(blocks, columns=2):
  cells = []
  for label, lines in blocks:
    cell = [Paragraph(esc(label).upper(), LABEL)]
    cell += [Paragraph(line, TEXT) for line in lines if line]
    cells.append(cell)
  while len(cells) % columns:
    cells.append("")
  rows = [cells[i:i + columns] for i in range(0, len(cells), columns)]
  table = Table(rows, colWidths=[PAGE_W / columns] * columns)
  table.setStyle(TableStyle([
    ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ("LEFTPADDING", (0, 0), (-1, -1), 0),
    ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
  ]))
  return table


def _items_table(header, rows, widths, right_from):
  def cells(values, left, right):
    return [
      v if isinstance(v, Paragraph) else Paragraph(esc(v), right if i >= right_from else left)
      for i, v in enumerate(values)
    ]

  data = [cells(header, HEAD, HEAD_R)] + [cells(r, CELL, CELL_R) for r in rows]
  table = Table(data, colWidths=[PAGE_W * w for w in widths], repeatRows=1)
  table.setStyle(TableStyle([
    ("BACKGROUND", (0, 0), (-1, 0), HEAD_BG),
    ("LINEBELOW", (0, 0), (-1, -1), 0.5, LINE),
    ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ("TOPPADDING", (0, 0), (-1, -1), 5),
    ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
  ]))
  return table


def _notes(label, text):
  if not text:
    return []
  return [
    Spacer(1, 10),
    Paragraph(esc(label).upper(), LABEL),
    Paragraph(esc(text).replace("\n", "<br/>"), TEXT),
  ]


def _product_cell(rfq_item):
  return Paragraph(
    f'{esc(rfq_item.product_name)}<br/><font size="7.5" color="{MUTED.hexval()}">'
    f'{esc(rfq_item.sku)}</font>',
    CELL,
  )


def rfq_pdf(rfq):
  items = list(rfq.items.all())
  business = rfq.business
  expected = None
  if items:
    expected = rfq.created_at.date() + timedelta(days=items[0].product.lead_time_days)

  story = [
    _header("Request for Quotation", rfq.number, rfq.get_status_display()),
    Spacer(1, 12),
    _info_grid([
      ("Buyer", [f"<b>{esc(business.business_name)}</b>", esc(business.city)]),
      ("Quote by", [f"<b>{fmt_datetime(rfq.deadline)}</b>"]),
      ("Issued on", [fmt_datetime(rfq.created_at)]),
      ("Expected delivery", [fmt_date(expected)]),
    ]),
    Spacer(1, 6),
    Paragraph("Items requested", H2),
    Spacer(1, 4),
    _items_table(
      ["#", "Product", "SKU", "Category", "Quantity"],
      [
        [i, it.product_name, it.sku,
         it.product.category.name if it.product.category else "-", f"{it.quantity} units"]
        for i, it in enumerate(items, 1)
      ],
      widths=[0.06, 0.40, 0.20, 0.18, 0.16],
      right_from=4,
    ),
    *_notes("Notes from buyer", rfq.notes),
    Spacer(1, 14),
    Paragraph(
      "Please submit your quotation on Kosh before the deadline above. Prices should be "
      "per unit, excluding GST, with the GST rate stated separately.",
      SMALL,
    ),
  ]
  return _build(f"{rfq.number} - Request for Quotation", story)


def quotation_pdf(quotation):
  rfq = quotation.rfq
  supplier = quotation.supplier_profile
  supplier_email = getattr(supplier.user, "email", "")

  address = ", ".join(p for p in [supplier.address, supplier.city, supplier.pincode] if p)
  items = list(quotation.items.all())

  expected = None
  rfq_items = list(rfq.items.all())
  if rfq_items:
    expected = rfq.created_at.date() + timedelta(days=rfq_items[0].product.lead_time_days)
  delivery = fmt_date(quotation.delivery_date)
  if expected and quotation.delivery_date > expected:
    late = (quotation.delivery_date - expected).days
    delivery += f' <font color="{WARN.hexval()}">({late} day{"s" if late != 1 else ""} after expected)</font>'

  totals = [
    ("Subtotal", money(quotation.subtotal)),
    ("GST", money(quotation.tax_total)),
    ("<b>Total (incl. GST)</b>", f"<b>{money(quotation.grand_total)}</b>"),
    ("Advance payment", money(quotation.advance_amount)),
    ("Balance on delivery", money(quotation.grand_total - quotation.advance_amount)),
  ]
  totals_table = Table(
    [[Paragraph(k, CELL), Paragraph(v, CELL_R)] for k, v in totals],
    colWidths=[PAGE_W * 0.22, PAGE_W * 0.20],
    hAlign="RIGHT",
  )
  totals_table.setStyle(TableStyle([
    ("LINEABOVE", (0, 2), (-1, 2), 0.8, INK),
    ("LINEBELOW", (0, 2), (-1, 2), 0.8, INK),
    ("TOPPADDING", (0, 0), (-1, -1), 3),
    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
  ]))

  if quotation.advance_amount > 0:
    payment_terms = [
      f"{money(quotation.advance_amount)} advance",
      f"{money(quotation.grand_total - quotation.advance_amount)} on delivery",
    ]
  else:
    payment_terms = ["Full amount on delivery"]

  story = [
    _header("Quotation", f"For {rfq.number} - Revision {quotation.revision}",
            quotation.get_status_display()),
    Spacer(1, 12),
    _info_grid([
      ("From (supplier)", [
        f"<b>{esc(supplier.company_name)}</b>",
        esc(address),
        f"GSTIN: {esc(supplier.gstin)}",
        " | ".join(esc(x) for x in [supplier.phone, supplier_email] if x),
      ]),
      ("To (buyer)", [f"<b>{esc(rfq.business.business_name)}</b>", esc(rfq.business.city)]),
      ("Submitted on", [fmt_datetime(quotation.submitted_at)]),
      ("Valid until", [fmt_date(quotation.valid_until)]),
      ("Delivery date", [delivery]),
      ("Payment terms", payment_terms),
    ]),
    Spacer(1, 6),
    Paragraph("Items quoted", H2),
    Spacer(1, 4),
    _items_table(
      ["#", "Product", "Qty", "Unit price (Rs.)", "GST", "Taxable (Rs.)", "GST (Rs.)", "Total (Rs.)"],
      [
        [i, _product_cell(it.rfq_item), it.quantity, money(it.unit_price, False),
         pct(it.gst_rate), money(it.line_subtotal, False), money(it.line_tax, False),
         money(it.line_total, False)]
        for i, it in enumerate(items, 1)
      ],
      widths=[0.04, 0.27, 0.07, 0.13, 0.07, 0.15, 0.12, 0.15],
      right_from=2,
    ),
    Spacer(1, 8),
    totals_table,
    *_notes("Remarks", quotation.notes),
  ]
  return _build(f"{rfq.number} - Quotation from {supplier.company_name}", story)

def _totals_table(rows, bold_rows=()):
  data = []
  for i, (label, amount) in enumerate(rows):
    if i in bold_rows:
      label, amount = f"<b>{label}</b>", f"<b>{amount}</b>"
    data.append([Paragraph(label, CELL), Paragraph(amount, CELL_R)])
  table = Table(data, colWidths=[PAGE_W * 0.28, PAGE_W * 0.20], hAlign="RIGHT")
  style = [
    ("TOPPADDING", (0, 0), (-1, -1), 3),
    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
  ]
  for i in bold_rows:
    style.append(("LINEABOVE", (0, i), (-1, i), 0.8, INK))
    style.append(("LINEBELOW", (0, i), (-1, i), 0.8, INK))
  table.setStyle(TableStyle(style))
  return table


def supplier_lines(supplier):
  email = getattr(supplier.user, "email", "")
  address = ", ".join(p for p in [supplier.address, supplier.city, supplier.pincode] if p)
  return [
    f"<b>{esc(supplier.company_name)}</b>",
    esc(address),
    f"GSTIN: {esc(supplier.gstin)}",
    " | ".join(esc(x) for x in [supplier.phone, email] if x),
  ]


def buyer_lines(business):
  owner = business.owner
  name = getattr(getattr(owner, "profile", None), "name", "") or ""
  where = ", ".join(p for p in [business.business_type, business.city] if p)
  return [
    f"<b>{esc(business.business_name)}</b>",
    esc(where),
    esc(name),
    esc(owner.email),
  ]

def invoice_pdf(invoice):
  po = invoice.purchase_order
  shipment = getattr(po, "shipment", None)
  receipt = getattr(po, "goods_receipt", None)
  items = sorted(invoice.items.all(), key=lambda it: it.product_name.lower())

  dispatched = [fmt_datetime(shipment.dispatched_at) if shipment else "-"]
  expected = fmt_date(shipment.expected_delivery_date if shipment else po.delivery_date)
  if shipment:
    if shipment.tracking_note:
      dispatched.append(f"Tracking: {esc(shipment.tracking_note)}")
    if shipment.is_late:
      days = shipment.late_by_days
      expected += (
        f' <font color="{WARN.hexval()}">({days} day{"s" if days != 1 else ""} '
        f'after the promised date)</font>'
      )

  rows = [
    ("Subtotal", money(invoice.subtotal)),
    ("GST", money(invoice.tax_total)),
    ("Invoice total", money(invoice.grand_total)),
    ("Less: advance paid", money(invoice.advance_applied)),
  ]
  if invoice.discrepancy_credit > 0:
    rows.append(("Less: goods receipt credit", money(invoice.discrepancy_credit)))
  rows.append(("Balance payable", money(invoice.balance_due)))
  bold = (2, len(rows) - 1)
  if invoice.refund_due > 0:
    rows.append(("Advance refundable by supplier", money(invoice.refund_due)))

  if receipt:
    footnote = (
      f"Amounts include goods receipt {esc(receipt.number)}: shortages and rejected "
      "goods are credited above."
    )
  else:
    footnote = (
      "Generated automatically from the quantities dispatched. The balance may change "
      "once the buyer confirms delivery with a goods receipt."
    )

  story = [
    _header("Invoice", invoice.number, invoice.get_status_display()),
    Spacer(1, 12),
    _info_grid([
      ("From (supplier)", supplier_lines(invoice.supplier_profile)),
      ("Billed to (buyer)", buyer_lines(invoice.business)),
      ("Invoice date", [fmt_date(invoice.issue_date)]),
      ("Purchase order", [esc(po.number)]),
      ("Dispatched on", dispatched),
      ("Expected delivery", [expected]),
    ]),
    Spacer(1, 6),
    Paragraph("Items dispatched", H2),
    Spacer(1, 4),
    _items_table(
      ["#", "Product", "Qty", "Unit price (Rs.)", "GST", "Taxable (Rs.)", "GST (Rs.)", "Total (Rs.)"],
      [
        [i, _product_cell(it), it.quantity, money(it.unit_price, False),
         pct(it.gst_rate), money(it.line_subtotal, False), money(it.line_tax, False),
         money(it.line_total, False)]
        for i, it in enumerate(items, 1)
      ],
      widths=[0.04, 0.27, 0.07, 0.13, 0.07, 0.15, 0.12, 0.15],
      right_from=2,
    ),
    Spacer(1, 8),
    _totals_table(rows, bold_rows=bold),
    Spacer(1, 14),
    Paragraph(footnote, SMALL),
  ]
  return _build(f"{invoice.number} - Invoice from {invoice.supplier_profile.company_name}", story)
